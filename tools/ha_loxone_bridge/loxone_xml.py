"""Render the Loxone Virtual Output template (shape copied from Loxone Config's export)."""
from __future__ import annotations

import xml.etree.ElementTree as ET
from pathlib import Path

from .mapping import LOXONE_TO_HA, BridgeMapping, Point

# Same structure Loxone Config exports ("Als Vorlage speichern"): Info element first,
# UTF-8 with BOM, tab indent.
INFO_ATTRS = {"templateType": "3", "minVersion": "17010630"}


def webhook_path(p: Point) -> str:
    return f"/api/webhook/{p.webhook_id}"


def _cmd_attrs(p: Point) -> dict[str, str]:
    base = webhook_path(p)
    if p.is_switch:
        # Digital output: fixed 1 for On, 0 for Off (Off is sent once on the edge, not repeated).
        on_cmd, off_cmd = f"{base}?v=1", f"{base}?v=0"
        comment = f"{p.ha_entity} 0/1"
    else:
        # Analog output has no Off command; <v> is the value placeholder of a Virtual Output.
        on_cmd, off_cmd = f"{base}?v=<v>", ""
        comment = f"{p.ha_entity} value"
    attrs = {
        "Title": p.loxone_name,
        "Comment": comment,
        "CmdOnMethod": "GET",
        "CmdOffMethod": "GET",
        "CmdOn": on_cmd,
        "CmdOnHTTP": "",
        "CmdOnPost": "",
        "CmdOff": off_cmd,
        "CmdOffHTTP": "",
        "CmdOffPost": "",
        "CmdAnswer": "",
        "Analog": "false" if p.is_switch else "true",
        "Repeat": str(p.repeat_seconds),
        "RepeatRate": str(p.repeat_seconds),
    }
    if not p.is_switch:
        attrs.update({"SourceValLow": "0", "DestValLow": "0", "SourceValHigh": "0", "DestValHigh": "0"})
    attrs["HintText"] = ""
    return attrs


def outgoing_points(mapping: BridgeMapping) -> list[Point]:
    return [p for p in mapping.points if p.direction == LOXONE_TO_HA]


def render_virtual_out(mapping: BridgeMapping) -> str:
    """Template text without BOM; one Virtual Output device pointing at Home Assistant."""
    root = ET.Element(
        "VirtualOut",
        {
            "HintText": "",
            "Title": f"HA Bridge - {mapping.title}",
            "Comment": "Generated by tools.ha_loxone_bridge; webhook ids are secrets, do not commit",
            "Address": f"http://{mapping.ha_host}:{mapping.ha_port}",
            "CmdInit": "",
            "CloseAfterSend": "true",
            "CmdSep": "",
        },
    )
    ET.SubElement(root, "Info", INFO_ATTRS)
    for p in outgoing_points(mapping):
        ET.SubElement(root, "VirtualOutCmd", _cmd_attrs(p))
    ET.indent(root, space="\t")
    body = ET.tostring(root, encoding="unicode").replace(" />", "/>")
    return '<?xml version="1.0" encoding="utf-8"?>\n' + body + "\n"


def write_template(path: Path, text: str) -> None:
    path.write_bytes(b"\xef\xbb\xbf" + text.encode("utf-8"))
